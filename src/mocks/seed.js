const userName = (id) => seedUsers.find((u) => u.id === id)?.fullName || '';
const sigOf = (userId) => seedSignatures.find((s) => s.userId === userId)?.imageUrl || makeSignatureSvg(userName(userId));

const item = (locationId, code, quantity, extra = {}) => {
  const asset = seedAssets.find((a) => a.id === `a_${locationId}_${code}`) || buildAsset(code, locationId, quantity);
  return {
    id: `item_${asset.id}`,
    assetId: asset.id,
    assetCode: code,
    assetName: asset.name,
    unit: asset.unit,
    categoryId: asset.categoryId,
    imageUrl: null,
    quantity,
    condition: 'GOOD',
    handoverQuantity: null,
    handoverCondition: null,
    handoverNote: '',
    handoverImages: [],
    receivedQuantity: null,
    receivedCondition: null,
    receivedNote: '',
    receivedImages: [],
    acceptedQuantity: null,
    cancelledQuantity: 0,
    ...extra,
  };
};

const signature = (type, userId, at, version = 1) => ({
  id: `ts_${type}_${userId}_${at}`,
  type,
  signedBy: userId,
  signedByName: userName(userId),
  signatureUrl: sigOf(userId),
  signedAt: at,
  documentVersion: version,
  valid: true,
  invalidatedAt: null,
  invalidReason: null,
});

const history = (action, userId, at, note = '', version = 1) => ({ id: `h_${action}_${at}`, action, userId, at, note, version });

const snapshotOf = (t) => ({
  type: t.type,
  fromCampusId: t.fromCampusId,
  toCampusId: t.toCampusId,
  fromLocationId: t.fromLocationId,
  toLocationId: t.toLocationId,
  reason: t.reason,
  note: t.note,
  expectedHandoverDate: t.expectedHandoverDate,
  handoverUserId: t.handoverUserId,
  receiverUserId: t.receiverUserId,
  items: t.items.map((i) => ({ assetId: i.assetId, assetCode: i.assetCode, assetName: i.assetName, unit: i.unit, quantity: i.quantity })),
});

const base = (t) => {
  const transfer = {
    attachments: [],
    signatures: [],
    revisions: [],
    revisionRequests: [],
    discrepancies: [],
    history: [],
    notifyOnSubmit: true,
    handoverPickMode: 'SUGGESTED',
    receiverPickMode: 'SUGGESTED',
    createdBy: 'u_lan',
    version: 1,
    note: '',
    ...t,
  };
  if (transfer.status !== 'DRAFT' && transfer.revisions.length === 0) {
    transfer.revisions = [
      {
        id: `rev_${t.id}_1`,
        version: 1,
        createdAt: t.createdAt,
        createdBy: transfer.createdBy,
        changeNote: 'Phiên bản đầu tiên',
        snapshot: snapshotOf(transfer),
        revisionRequestId: null,
      },
    ];
  }
  return transfer;
};

